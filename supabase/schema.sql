-- Tabla para mensajes del formulario de contacto
-- Ejecutar en el editor SQL de Supabase.

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text not null,
  email text not null,
  mensaje text not null,
  constraint contact_messages_nombre_len check (char_length(nombre) between 2 and 120),
  constraint contact_messages_email_len check (char_length(email) between 5 and 254),
  constraint contact_messages_mensaje_len check (char_length(mensaje) between 10 and 5000)
);

alter table public.contact_messages enable row level security;

-- Limpieza de políticas previas (idempotente para re-ejecución manual)
drop policy if exists "Allow anonymous inserts on contact_messages" on public.contact_messages;
drop policy if exists "Allow authenticated inserts on contact_messages" on public.contact_messages;

-- Inserción pública segura (anon/auth) desde el formulario del portfolio.
-- No se crean políticas SELECT/UPDATE/DELETE: sin lectura pública por defecto.
create policy "Allow anonymous inserts on contact_messages"
  on public.contact_messages
  for insert
  to anon
  with check (true);

create policy "Allow authenticated inserts on contact_messages"
  on public.contact_messages
  for insert
  to authenticated
  with check (true);

